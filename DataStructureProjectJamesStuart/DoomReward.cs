    public class DoomReward
    {
        
        public void launchDoom()
        {
            string doomFolder = Path.Combine(
                AppContext.BaseDirectory, "Doom");

            string exePath = Path.Combine(
                doomFolder, "chocolate-doom.exe");

            string wadPath = Path.Combine(
                doomFolder, "freedoom1.wad");
            

            if (!File.Exists(exePath) || !File.Exists(wadPath))
            {
                Console.WriteLine("DOOM files not found!");
                return;
            }

            Process.Start(new ProcessStartInfo
            {
                FileName = exePath,
                Arguments = $"-iwad \"{wadPath}\"",
                WorkingDirectory = doomFolder,
                UseShellExecute = false
            });
        }
        
    }
